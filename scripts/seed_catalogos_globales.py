def _upsert_catalogo(db, modelo, filas, columnas):
    """
    Inserta o actualiza filas de un catalogo por su clave primaria `codigo`.
    Reutilizable para cualquier catalogo global de clave simple (codigo, *resto).
    Retorna la cantidad de filas nuevas insertadas (no cuenta las ya existentes).
    """
    insertados = 0
    for fila in filas:
        datos = dict(zip(columnas, fila))
        existente = db.get(modelo, datos["codigo"])
        if existente is None:
            db.add(modelo(**datos))
            insertados += 1
        else:
            for campo, valor in datos.items():
                setattr(existente, campo, valor)
    db.commit()
    return insertados


def _parse_csv(texto):
    """Parsea un bloque CSV embebido (codigo,nombre[,extra]) ignorando lineas vacias."""
    lector = csv.reader(io.StringIO(texto.strip()))
    return [tuple(c.strip() for c in fila) for fila in lector if fila]


